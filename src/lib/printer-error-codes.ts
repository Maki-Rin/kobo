// 公式一覧にないが、同社の他機種（AD5X）で報告されているもの
const reported: Record<string, string> = {
  E0113: 'フィラメントセンサーまたはフィラメント経路の異常の可能性',
};

export function errorCodeMeaning(code: string): { text: string; official: boolean } | null {
  const key = code.toUpperCase();
  if (official[key]) return { text: official[key], official: true };
  if (reported[key]) return { text: reported[key], official: false };
  return null;
}
